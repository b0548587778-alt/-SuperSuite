// הסתרת מזהים לפני שליחת טקסט ל-AI (ענן בעתיד, ויומן תקלות). פונקציה טהורה — בלי Electron ובלי רשת.
// הכלל: עדיף להסתיר יותר מדי מאשר לשלוח פרט מזהה.

const PII = Object.freeze([
  // כתובת דוא"ל
  { kind: 'email', re: /[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/g, mask: '[דוא״ל]' },
  // מספר כרטיס בקבוצות עם רווחים או מקפים (13–19 ספרות): 4-4-4-1..4, ‏4-4-4-4-1..3, ‏4-6-5 (אמריקן אקספרס) — לפני ת"ז וטלפון.
  // רצף בלי מפרידים נתפס ב-longNum (סקירת קוד 2.11.2026)
  { kind: 'card', re: /(?<![\d.,])(?:\d{4}([ -])\d{4}\1\d{4}\1\d{4}(?:\1\d{1,3})?|\d{4}([ -])\d{6}\2\d{5}|\d{4}([ -])\d{4}\3\d{4}\3\d{1,3})(?![\d,]|\.\d)/g, mask: '[כרטיס]' },
  // ת"ז / ח"פ — 9 ספרות, בשלושה סגנונות בלבד:
  //   רצף        123456789   — לא ספרה לפני ולא אחרי, ולא „.”+ספרה אחריו („123456789.” הוא סכום בסוף משפט)
  //   מקפים      123-456-789 — „.” לפניו מותר (אחרי „ת"ז:”), ספרה לפניו אסורה („012-345-6789” — 10 ספרות)
  //   נקודות     987.654.321 — לא ספרה/„.” לפני (גם „2026.10.05” נופל כאן, לא „05.2026.10”), ולא ספרה אחרי
  // 9 ספרות עם נקודה צמודה („123456789.5”) נשארות — זה סכום, לא ת"ז
  // „בלי מפריד” בסוף = לא המשך של מספר ארוך: „1000123456789” מותר רק ב-longNum למטה
  // (ברצף אין lookbehind אחרי הספרות — הוא בודק רק את מה שלפני, כמו במקפים ובנקודות)
  { kind: 'id', re: /(?:(?<![\d.\-])\d{9}(?=$|[^\d.]|\.[^\d])|(?<![\d.])(\d{3})[-\s](\d{3})[-\s](\d{3})(?=$|[^\d.]|\.[^\d])|(?<![\d.])(\d{3})\.(\d{3})\.(\d{3})(?=$|[^\d.]|\.[^\d]))/g, mask: '[ת״ז]' },
  // טלפון ישראלי — כמו ב-shell/logger.js: 05X / 07X (077, 072...) / 0X קווי, עם +972 או 0, קידומת בסוגריים,
  // ומפרידים (מקף, רווח, נקודה) גם בתוך 7 הספרות („050-123-45-67”). פעם 07X ו„(02) 123-4567” נשארו גלויים (סקירת קוד 2.11.2026)
  { kind: 'phone', re: /(?<![\d+])(?:\+972[-\s.]?\(?0?|\(?0)(?:[5-7]\d|[2-489])\)?[-\s.]?\d(?:[-\s.]?\d){6}(?!\d|\.\d)/g, mask: '[טלפון]' },
  // מספר חשבון בנק ארוך (7+ ספרות רצופות) — נכלל במסלול של נתיבים ומספרים
  { kind: 'longNum', re: /(?<![\d.,])\d{7,}(?![\d.,])/g, mask: '[מספר]' },
  // נתיבי Windows / Unix — שם המשתמש בנתיב עלול לזהות את האדם
  { kind: 'path', re: /(?:[A-Za-z]:\\|\\\\)[^\s"'<>|]*/g, mask: '[נתיב]' },
  { kind: 'path', re: /(?:\/Users\/|\/home\/|~\/)[^\s"'<>|]*/g, mask: '[נתיב]' },
]);

// מחזיר { text, hits: { email, card, id, phone, longNum, path } } — hits לספירה בלבד, בלי הערכים עצמם
function redact(input) {
  let text = String(input == null ? '' : input);
  const hits = { email: 0, card: 0, id: 0, phone: 0, longNum: 0, path: 0 };
  for (const p of PII) {
    text = text.replace(p.re, (...args) => {
      hits[p.kind] += 1;
      return p.mask;
    });
  }
  return { text, hits };
}

module.exports = { redact, PII };
